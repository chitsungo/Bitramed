create or replace function public.admin_import_past_paper_units()
returns integer
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_row public.import_past_paper_units%rowtype;
  v_set_id uuid;
  v_unit_id uuid;
  v_set_key text;
  v_imported integer := 0;
begin
  perform public.require_current_user_admin();

  for v_row in
    select *
    from public.import_past_paper_units
    where processed_at is null
    order by id
  loop
    begin
      v_set_key := nullif(trim(coalesce(v_row.set_key, '')), '');
      if v_set_key is null then
        v_set_key := md5(
          concat_ws(
            '|||',
            v_row.year_label,
            v_row.paper_group_label,
            v_row.topic_label,
            v_row.set_title
          )
        );
      end if;

      insert into public.past_paper_sets (
        set_key,
        title,
        year_label,
        paper_group_label,
        topic_label
      )
      values (
        v_set_key,
        trim(v_row.set_title),
        trim(coalesce(v_row.year_label, '')),
        trim(coalesce(v_row.paper_group_label, 'Past Papers')),
        trim(coalesce(v_row.topic_label, ''))
      )
      on conflict (set_key)
      do update set
        title = excluded.title,
        year_label = excluded.year_label,
        paper_group_label = excluded.paper_group_label,
        topic_label = excluded.topic_label
      returning id into v_set_id;

      insert into public.past_paper_units (
        set_id,
        stem,
        display_order
      )
      values (
        v_set_id,
        trim(v_row.stem),
        coalesce(v_row.unit_order, v_row.id::integer)
      )
      returning id into v_unit_id;

      insert into public.past_paper_branches (
        unit_id,
        branch_order,
        prompt,
        correct_answer,
        explanation
      )
      values
        (v_unit_id, 1, trim(v_row.branch_1_prompt), public.normalize_past_paper_answer(v_row.branch_1_answer), nullif(trim(coalesce(v_row.branch_1_explanation, '')), '')),
        (v_unit_id, 2, trim(v_row.branch_2_prompt), public.normalize_past_paper_answer(v_row.branch_2_answer), nullif(trim(coalesce(v_row.branch_2_explanation, '')), '')),
        (v_unit_id, 3, trim(v_row.branch_3_prompt), public.normalize_past_paper_answer(v_row.branch_3_answer), nullif(trim(coalesce(v_row.branch_3_explanation, '')), '')),
        (v_unit_id, 4, trim(v_row.branch_4_prompt), public.normalize_past_paper_answer(v_row.branch_4_answer), nullif(trim(coalesce(v_row.branch_4_explanation, '')), '')),
        (v_unit_id, 5, trim(v_row.branch_5_prompt), public.normalize_past_paper_answer(v_row.branch_5_answer), nullif(trim(coalesce(v_row.branch_5_explanation, '')), ''));

      update public.import_past_paper_units
      set processed_at = now(),
          error_message = null
      where id = v_row.id;

      v_imported := v_imported + 1;
    exception
      when others then
        update public.import_past_paper_units
        set error_message = sqlerrm
        where id = v_row.id;
    end;
  end loop;

  return v_imported;
end;
$$;

create or replace function public.app_past_paper_catalog()
returns table (
  set_id uuid,
  title text,
  year_label text,
  paper_group_label text,
  topic_label text,
  unit_count integer,
  total_marks integer,
  attempt_count integer,
  best_percentage integer,
  latest_percentage integer
)
language sql
stable
security definer
set search_path to 'public'
as $$
  with guard as (
    select public.app_require_active_access() as ok
  ),
  unit_counts as (
    select
      ns.id as set_id,
      count(distinct nu.id)::int as unit_count,
      count(nb.id)::int as total_marks
    from public.past_paper_sets ns
    left join public.past_paper_units nu
      on nu.set_id = ns.id
     and nu.is_active
    left join public.past_paper_branches nb
      on nb.unit_id = nu.id
    group by ns.id
  ),
  attempts as (
    select
      set_id,
      count(*)::int as attempt_count,
      max(percentage)::int as best_percentage,
      (array_agg(percentage order by completed_at desc, id desc))[1]::int as latest_percentage
    from public.past_paper_attempts
    where user_id = auth.uid()
    group by set_id
  )
  select
    ns.id,
    ns.title,
    ns.year_label,
    ns.paper_group_label,
    ns.topic_label,
    coalesce(uc.unit_count, 0),
    coalesce(uc.total_marks, 0),
    coalesce(a.attempt_count, 0),
    coalesce(a.best_percentage, 0),
    coalesce(a.latest_percentage, 0)
  from guard
  cross join public.past_paper_sets ns
  left join unit_counts uc on uc.set_id = ns.id
  left join attempts a on a.set_id = ns.id
  where ns.is_active
  order by ns.display_order, ns.year_label, ns.paper_group_label, ns.topic_label, ns.title;
$$;

create or replace function public.app_past_paper_years()
returns table (
  year_label text,
  paper_group_label text,
  topic_count integer,
  exam_count integer,
  unit_count integer,
  total_marks integer,
  attempt_count integer,
  best_percentage integer
)
language sql
stable
security definer
set search_path to 'public'
as $$
  with catalog as (
    select *
    from public.app_past_paper_catalog()
  )
  select
    year_label,
    paper_group_label,
    count(distinct topic_label)::int as topic_count,
    count(distinct set_id)::int as exam_count,
    sum(unit_count)::int as unit_count,
    sum(total_marks)::int as total_marks,
    sum(attempt_count)::int as attempt_count,
    coalesce(max(nullif(best_percentage, 0)), 0)::int as best_percentage
  from catalog
  group by year_label, paper_group_label
  order by year_label, paper_group_label;
$$;

