create or replace function public.app_past_paper_units(p_set_id uuid)
returns table (
  unit_id uuid,
  stem text,
  image_url text,
  display_order integer,
  branches jsonb
)
language sql
stable
security definer
set search_path to 'public'
as $$
  with guard as (
    select public.app_require_active_access() as ok
  )
  select
    nu.id,
    nu.stem,
    nu.image_url,
    nu.display_order,
    jsonb_agg(
      jsonb_build_object(
        'branchId', nb.id,
        'order', nb.branch_order,
        'prompt', nb.prompt,
        'imageUrl', nb.image_url
      )
      order by nb.branch_order
    ) as branches
  from guard
  cross join public.past_paper_units nu
  join public.past_paper_sets ns
    on ns.id = nu.set_id
   and ns.is_active
  join public.past_paper_branches nb
    on nb.unit_id = nu.id
  where nu.set_id = p_set_id
    and nu.is_active
  group by nu.id
  having count(nb.id) = 5
  order by nu.display_order, nu.id;
$$;

create or replace function public.app_submit_past_paper_attempt(
  p_set_id uuid,
  p_answers jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_attempt_id bigint;
  v_score integer := 0;
  v_total integer := 0;
  v_correct integer := 0;
  v_wrong integer := 0;
  v_unanswered integer := 0;
  v_branch record;
  v_answer_text text;
  v_user_answer boolean;
  v_is_correct boolean;
begin
  perform public.app_require_active_access();

  if p_set_id is null then
    raise exception 'Set id is required.';
  end if;

  if not exists (
    select 1
    from public.past_paper_sets
    where id = p_set_id
      and is_active
  ) then
    raise exception 'Past paper set not found.';
  end if;

  insert into public.past_paper_attempts (user_id, set_id)
  values (auth.uid(), p_set_id)
  returning id into v_attempt_id;

  for v_branch in
    select
      nu.id as unit_id,
      nb.id as branch_id,
      nb.correct_answer
    from public.past_paper_units nu
    join public.past_paper_branches nb on nb.unit_id = nu.id
    where nu.set_id = p_set_id
      and nu.is_active
    order by nu.display_order, nb.branch_order
  loop
    v_total := v_total + 1;
    v_answer_text := p_answers ->> v_branch.branch_id::text;

    if v_answer_text is null then
      v_user_answer := null;
      v_is_correct := false;
      v_unanswered := v_unanswered + 1;
    else
      v_user_answer := public.normalize_past_paper_answer(v_answer_text);
      v_is_correct := v_user_answer = v_branch.correct_answer;
      if v_is_correct then
        v_score := v_score + 1;
        v_correct := v_correct + 1;
      else
        v_wrong := v_wrong + 1;
      end if;
    end if;

    insert into public.past_paper_attempt_answers (
      attempt_id,
      unit_id,
      branch_id,
      user_answer,
      correct_answer,
      is_correct,
      points
    )
    values (
      v_attempt_id,
      v_branch.unit_id,
      v_branch.branch_id,
      v_user_answer,
      v_branch.correct_answer,
      v_is_correct,
      case when v_is_correct then 1 else 0 end
    );
  end loop;

  update public.past_paper_attempts
  set
    score = v_score,
    total_marks = v_total,
    correct_count = v_correct,
    wrong_count = v_wrong,
    unanswered_count = v_unanswered,
    percentage = case when v_total > 0 then round((v_score::numeric / v_total::numeric) * 100)::int else 0 end
  where id = v_attempt_id;

  return jsonb_build_object(
    'attemptId', v_attempt_id,
    'score', v_score,
    'totalMarks', v_total,
    'correct', v_correct,
    'wrong', v_wrong,
    'unanswered', v_unanswered,
    'percentage', case when v_total > 0 then round((v_score::numeric / v_total::numeric) * 100)::int else 0 end
  );
end;
$$;

create or replace function public.app_past_paper_attempt_review(p_attempt_id bigint)
returns jsonb
language sql
stable
security definer
set search_path to 'public'
as $$
  with guard as (
    select public.app_require_active_access() as ok
  ),
  attempt as (
    select *
    from public.past_paper_attempts
    where id = p_attempt_id
      and user_id = auth.uid()
  ),
  units as (
    select
      nu.id as unit_id,
      nu.stem,
      nu.image_url,
      nu.display_order,
      jsonb_agg(
        jsonb_build_object(
          'branchId', nb.id,
          'order', nb.branch_order,
          'prompt', nb.prompt,
          'userAnswer', naa.user_answer,
          'correctAnswer', naa.correct_answer,
          'isCorrect', naa.is_correct,
          'points', naa.points,
          'explanation', nb.explanation
        )
        order by nb.branch_order
      ) as branches
    from attempt a
    join public.past_paper_units nu on nu.set_id = a.set_id
    join public.past_paper_branches nb on nb.unit_id = nu.id
    left join public.past_paper_attempt_answers naa
      on naa.attempt_id = a.id
     and naa.branch_id = nb.id
    group by nu.id
  )
  select jsonb_build_object(
    'attempt', jsonb_build_object(
      'attemptId', a.id,
      'setId', a.set_id,
      'score', a.score,
      'totalMarks', a.total_marks,
      'correct', a.correct_count,
      'wrong', a.wrong_count,
      'unanswered', a.unanswered_count,
      'percentage', a.percentage,
      'completedAt', a.completed_at
    ),
    'units', coalesce(
      jsonb_agg(
        jsonb_build_object(
          'unitId', u.unit_id,
          'stem', u.stem,
          'imageUrl', u.image_url,
          'branches', u.branches
        )
        order by u.display_order, u.unit_id
      ),
      '[]'::jsonb
    )
  )
  from guard
  cross join attempt a
  left join units u on true
  group by a.id, a.set_id, a.score, a.total_marks, a.correct_count, a.wrong_count, a.unanswered_count, a.percentage, a.completed_at;
$$;

