-- Isolated Past Papers grouped true/false exam system.
-- This intentionally does not reference public.quizzes, public.questions,
-- public.quiz_attempts, public.import_tf, or public.import_sba.

create table if not exists public.past_paper_sets (
  id uuid primary key default gen_random_uuid(),
  set_key text not null unique,
  title text not null,
  year_label text not null default '',
  paper_group_label text not null default 'Past Papers',
  topic_label text not null default '',
  description text,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.past_paper_units (
  id uuid primary key default gen_random_uuid(),
  set_id uuid not null references public.past_paper_sets(id) on delete cascade,
  stem text not null,
  image_url text,
  explanation text,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.past_paper_branches (
  id uuid primary key default gen_random_uuid(),
  unit_id uuid not null references public.past_paper_units(id) on delete cascade,
  branch_order integer not null,
  prompt text not null,
  correct_answer boolean not null,
  explanation text,
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint past_paper_branches_order_check check (branch_order between 1 and 5),
  constraint past_paper_branches_unit_order_unique unique (unit_id, branch_order)
);

create table if not exists public.past_paper_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  set_id uuid not null references public.past_paper_sets(id) on delete cascade,
  score integer not null default 0,
  total_marks integer not null default 0,
  correct_count integer not null default 0,
  wrong_count integer not null default 0,
  unanswered_count integer not null default 0,
  percentage integer not null default 0,
  completed_at timestamptz not null default now()
);

create table if not exists public.past_paper_attempt_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references public.past_paper_attempts(id) on delete cascade,
  unit_id uuid not null references public.past_paper_units(id) on delete cascade,
  branch_id uuid not null references public.past_paper_branches(id) on delete cascade,
  user_answer boolean,
  correct_answer boolean not null,
  is_correct boolean not null default false,
  points integer not null default 0,
  answered_at timestamptz not null default now(),
  constraint past_paper_attempt_answers_unique unique (attempt_id, branch_id)
);

create table if not exists public.import_past_paper_units (
  id bigint generated by default as identity primary key,
  set_key text,
  set_title text not null,
  year_label text not null default '',
  paper_group_label text not null default 'Past Papers',
  topic_label text not null default '',
  unit_order integer,
  stem text not null,
  branch_1_prompt text not null,
  branch_1_answer text not null,
  branch_1_explanation text,
  branch_2_prompt text not null,
  branch_2_answer text not null,
  branch_2_explanation text,
  branch_3_prompt text not null,
  branch_3_answer text not null,
  branch_3_explanation text,
  branch_4_prompt text not null,
  branch_4_answer text not null,
  branch_4_explanation text,
  branch_5_prompt text not null,
  branch_5_answer text not null,
  branch_5_explanation text,
  source_note text,
  imported_at timestamptz not null default now(),
  processed_at timestamptz,
  error_message text
);

create index if not exists past_paper_sets_browse_idx
  on public.past_paper_sets (is_active, display_order, year_label, paper_group_label, topic_label, title);

create index if not exists past_paper_units_set_idx
