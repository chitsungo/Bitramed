create or replace function public.normalize_past_paper_answer(p_answer text)
returns boolean
language plpgsql
immutable
set search_path to 'public'
as $$
declare
  v_answer text := lower(trim(coalesce(p_answer, '')));
begin
  if v_answer in ('t', 'true', 'yes', 'y', '1') then
    return true;
  end if;

  if v_answer in ('f', 'false', 'no', 'n', '0') then
    return false;
  end if;

  raise exception 'Invalid past paper answer: %. Use true/false or T/F.', p_answer;
end;
$$;

